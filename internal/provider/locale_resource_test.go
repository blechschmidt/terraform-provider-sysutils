const testLocaleResource = "sysutils_locale.test"

func localeResourceConfig(root, attrs string) string {
	p := ""
	if root != "" {
		p = rootedProvider(root)
	}
	return p + fmt.Sprintf(`
resource "sysutils_locale" "test" {
%s
}
`, attrs)
}

func TestAccLocale_rootDirDebian(t *testing.T) {
	root := testRootDir(t)
	mustWrite(t, filepath.Join(root, "etc/debian_version"), "12.5\n")
	p := filepath.Join(root, "etc/default/locale")
	const orig = "#  File generated by update-locale\nLANG=\"C.UTF-8\"\nLANGUAGE=en_US:en\n"
	mustWrite(t, p, orig)
	mustChmod(t, p, 0o640)
	config := func(attrs string) string {
		return localeResourceConfig(root, "  restore_on_destroy = true\n"+attrs)
	}

	resource.Test(t, resource.TestCase{
		ProtoV6ProviderFactories: testAccProtoV6ProviderFactories,
		// Destroy puts back the LANG and LC_* assignments, not the rest of
		// the file, which was deleted and recreated by the steps below.
		CheckDestroy: checkFileContent(p, "LANG=C.UTF-8\n"),
		Steps: []resource.TestStep{
			{
				Config: config(`  lang = "en_US.UTF-8"
  lc = {
    LC_TIME  = "en_GB.UTF-8"
    LC_PAPER = "de_DE.UTF-8"
  }`),
				Check: resource.ComposeAggregateTestCheckFunc(
					checkFileContent(p, "#  File generated by update-locale\nLANG=en_US.UTF-8\nLANGUAGE=en_US:en\nLC_TIME=en_GB.UTF-8\nLC_PAPER=de_DE.UTF-8\n"),
					checkFileMode(p, 0o640),
					checkNoTempFiles(filepath.Dir(p)),
					resource.TestCheckResourceAttr(testLocaleResource, "id", "system"),
					resource.TestCheckResourceAttr(testLocaleResource, "path", "/etc/default/locale"),
					resource.TestCheckResourceAttr(testLocaleResource, "generate", "false"),
					resource.TestCheckResourceAttr(testLocaleResource, "lc.%", "2"),
				),
			},
			{
				Config: config(`  lang = "en_US.UTF-8"
  lc = {
    LC_TIME  = "en_GB.UTF-8"
    LC_PAPER = "de_DE.UTF-8"
  }`),
				ConfigPlanChecks: resource.ConfigPlanChecks{
					PreApply: []plancheck.PlanCheck{plancheck.ExpectEmptyPlan()},
				},
			},
			{
				// Changed outside Terraform: LANG edited, LC_ALL added.
				PreConfig: setFile(t, p, "LANG=de_DE.UTF-8\nLANGUAGE=en_US:en\nLC_TIME=en_GB.UTF-8\nLC_PAPER=de_DE.UTF-8\nLC_ALL=C\n"),
				Config: config(`  lang = "en_US.UTF-8"
  lc = {
    LC_TIME  = "en_GB.UTF-8"
    LC_PAPER = "de_DE.UTF-8"
  }`),
				ConfigPlanChecks: resource.ConfigPlanChecks{
					PreApply: []plancheck.PlanCheck{plancheck.ExpectResourceAction(testLocaleResource, plancheck.ResourceActionUpdate)},
				},
				Check: checkFileContent(p, "LANG=en_US.UTF-8\nLANGUAGE=en_US:en\nLC_TIME=en_GB.UTF-8\nLC_PAPER=de_DE.UTF-8\n"),
			},
			{
				// Removing lc removes the LC_* variables.
				Config: config(`  lang = "de_DE.UTF-8"`),
				Check: resource.ComposeAggregateTestCheckFunc(
					checkFileContent(p, "LANG=de_DE.UTF-8\nLANGUAGE=en_US:en\n"),
					resource.TestCheckNoResourceAttr(testLocaleResource, "lc.%"),
				),
			},
			{
				// The file was deleted.
				PreConfig: func() { _ = os.Remove(p) },
				Config:    config(`  lang = "de_DE.UTF-8"`),
				ConfigPlanChecks: resource.ConfigPlanChecks{
					PreApply: []plancheck.PlanCheck{plancheck.ExpectResourceAction(testLocaleResource, plancheck.ResourceActionUpdate)},
				},
				Check: checkFileContent(p, "LANG=de_DE.UTF-8\n"),
			},
			{
				Config:                  config(`  lang = "de_DE.UTF-8"`),
				ResourceName:            testLocaleResource,
				ImportState:             true,
				ImportStateId:           "system",
				ImportStateVerify:       true,
				ImportStateVerifyIgnore: []string{"restore_on_destroy"},
			},
		},
	})
}

