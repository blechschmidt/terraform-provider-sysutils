func TestAccLocale_errors(t *testing.T) {
	root := testRootDir(t)
	mustMkdir(t, filepath.Join(root, "etc"))
	target := filepath.Join(root, "target")
	mustWrite(t, target, "LANG=C\n")
	mustSymlink(t, "/target", filepath.Join(root, "etc/locale.conf"))
	resource.Test(t, resource.TestCase{
		ProtoV6ProviderFactories: testAccProtoV6ProviderFactories,
		Steps: []resource.TestStep{
			{
				Config:      localeResourceConfig(root, `  lang = "en_US.UTF-8\nLC_ALL=C"`),
				ExpectError: regexp.MustCompile(`must\s+be\s+a\s+locale\s+name`),
			},
			{
				Config:      localeResourceConfig(root, "  lang = \"C\"\n  lc = { LC_ALL = \"C\" }"),
				ExpectError: regexp.MustCompile(`not\s+a\s+locale\s+category\s+variable`),
			},
			{
				Config:      localeResourceConfig(root, "  lang = \"C\"\n  lc = { LC_TIME = \"$(id)\" }"),
				ExpectError: regexp.MustCompile(`must\s+be\s+a\s+locale\s+name`),
			},
			{
				Config:      localeResourceConfig(root, "  lang = \"C\"\n  generate = true"),
				ExpectError: regexp.MustCompile(`(?s)Not\s+supported\s+with\s+root_dir`),
			},
			{
				// A symlink at the path is refused.
				Config:      localeResourceConfig(root, `  lang = "C"`),
				ExpectError: regexp.MustCompile(`is\s+a\s+symbolic\s+link;\s+refusing\s+to\s+follow\s+it`),
			},
			{
				Config:        localeResourceConfig(root, `  lang = "C"`),
				ResourceName:  testLocaleResource,
				ImportState:   true,
				ImportStateId: "/etc/locale.conf",
				ExpectError:   regexp.MustCompile(`import\s+ID\s+of\s+sysutils_locale\s+must\s+be\s+"system"`),
			},
		},
	})
	if err := checkFileContent(target, "LANG=C\n")(nil); err != nil {
		t.Error(err)
	}
}

